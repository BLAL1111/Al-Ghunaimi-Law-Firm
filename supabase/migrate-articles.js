async function main() {
  console.log(`source article count: ${articles.length}`);
  if (dryRun) {
    console.log('[dry-run] would upsert:');
    articles.forEach(a => console.log(` - ${a.slug} (${a.category})`));
    return;
  }
  const supabase = createClient(url, serviceKey);

  // Backup: export existing articles
  const { data: existing, error: fetchErr } = await supabase.from('articles').select('slug,title,status');
  if (fetchErr) console.warn('fetch existing failed:', fetchErr.message);
  else {
    const backupPath = `supabase/backup-articles-${new Date().toISOString().slice(0,10)}.json`;
    fs.writeFileSync(backupPath, JSON.stringify(existing, null, 2), 'utf8');
    console.log(`backup written to ${backupPath} (${existing.length} records)`);
  }

  let migrated = 0, skipped = 0, errors = 0;
  for (const a of articles) {
    const payload = {
      slug: a.slug,
      title: a.title,
      excerpt: a.excerpt,
      content_html: a.content_html,
      category: a.category,
      tags: a.tags,
      cover_image_url: null,
      cover_image_alt: null,
      author_name: a.author_name,
      published_at: a.published_at,
      status: 'published',
      seo_title: a.seo_title,
      seo_description: a.seo_description,
      og_image_url: null,
      canonical_path: `/articles/${a.slug}`,
      related_service_slug: a.related_service_slug,
      featured: false,
    };
    const { error } = await supabase.from('articles').upsert(payload, { onConflict: 'slug' });
    if (error) {
      console.error(`✗ ${a.slug}: ${error.message}`);
      errors++;
    } else {
      // verify
      const { data } = await supabase.from('articles').select('slug').eq('slug', a.slug).single();
      if (data) migrated++;
      else skipped++;
      console.log(`✓ ${a.slug}`);
    }
  }
  const { count: dbCount } = await supabase.from('articles').select('*', { count: 'exact', head: true });
  console.log(`\ndatabase article count: ${dbCount}`);
  console.log(`migrated: ${migrated}`);
  console.log(`skipped: ${skipped}`);
  console.log(`errors: ${errors}`);
}

main().catch(e => { console.error(e); process.exit(1); });
